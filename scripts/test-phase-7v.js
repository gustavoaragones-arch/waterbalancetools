#!/usr/bin/env node
'use strict';
/**
 * test-phase-7v.js (Phase 7V)
 *
 * Categories required by the Phase 7V spec:
 *  Direction (raise/lower/balanced), Magnitude (deterministic tiers),
 *  Numeric-dose prohibition (no ounce/lb dose, no live use of 5/6, no
 *  legacy path callable), Safety (retest/incremental guidance present),
 *  plus the established A-O style regression categories from prior phases
 *  (unrelated calculators unchanged, no LSI/bromine, no scope violations,
 *  ledger completeness).
 */
const fs = require('fs');
const path = require('path');
const assert = require('assert');
const { execSync } = require('child_process');

const ROOT = path.join(__dirname, '..');
const BASELINE_COMMIT = '4de88b8';
let passed = 0;
let failed = 0;

function test(name, fn) {
  try {
    fn();
    console.log(`PASS: ${name}`);
    passed++;
  } catch (e) {
    console.error(`FAIL: ${name}`);
    console.error(`   ${e.message}`);
    failed++;
  }
}

global.window = {};
delete require.cache[require.resolve(path.join(ROOT, 'js', 'calc-utils.js'))];
delete require.cache[require.resolve(path.join(ROOT, 'js', 'calculator.js'))];
require(path.join(ROOT, 'js', 'calc-utils.js'));
require(path.join(ROOT, 'js', 'calculator.js'));
const cu = global.window.WaterBalance.calcUtils;
const c = global.window.WaterBalance.calculator;
const REPORT_DIR = path.join(ROOT, 'reports', 'phase-7v');

// --- Direction ---
test('Direction: current pH < target pH -> raise', () => {
  const r = cu.calculatePHAdjustment(15000, 7.2, 7.4);
  assert.strictEqual(r.direction, 'raise');
});
test('Direction: current pH > target pH -> lower', () => {
  const r = cu.calculatePHAdjustment(15000, 7.8, 7.4);
  assert.strictEqual(r.direction, 'lower');
});
test('Direction: current pH = target pH -> balanced', () => {
  const r = cu.calculatePHAdjustment(15000, 7.4, 7.4);
  assert.strictEqual(r.direction, 'balanced');
  assert.strictEqual(r.magnitude, null);
});
test('Direction: within deadband (0.03 diff) -> balanced', () => {
  const r = cu.calculatePHAdjustment(15000, 7.37, 7.4);
  assert.strictEqual(r.direction, 'balanced');
});

// --- Magnitude (deterministic) ---
test('Magnitude: 0.1 diff -> small', () => {
  const r = cu.calculatePHAdjustment(15000, 7.3, 7.4);
  assert.strictEqual(r.magnitude, 'small');
});
test('Magnitude: 0.3 diff -> moderate', () => {
  const r = cu.calculatePHAdjustment(15000, 7.1, 7.4);
  assert.strictEqual(r.magnitude, 'moderate');
});
test('Magnitude: 0.6 diff -> substantial', () => {
  const r = cu.calculatePHAdjustment(15000, 8.0, 7.4);
  assert.strictEqual(r.magnitude, 'substantial');
});
test('Magnitude: boundary values are deterministic and repeatable', () => {
  const a = cu.calculatePHAdjustment(15000, 7.2, 7.4);
  const b = cu.calculatePHAdjustment(15000, 7.2, 7.4);
  assert.deepStrictEqual(a, b);
});
test('Magnitude: js/calculator.js evaluatePHGuidance agrees with js/calc-utils.js for the same diff', () => {
  const a = cu.calculatePHAdjustment(15000, 7.1, 7.4);
  const b = c.evaluatePHGuidance(15000, 0.3);
  assert.strictEqual(a.direction, b.direction);
  assert.strictEqual(a.magnitude, b.magnitude);
});

// --- Numeric-dose prohibition ---
test('No numeric pH dose is returned by calculatePHAdjustment', () => {
  const r = cu.calculatePHAdjustment(15000, 7.1, 7.4);
  assert.strictEqual(r.ounces, undefined, 'result must not contain an ounces field');
  assert.strictEqual(r.pounds, undefined, 'result must not contain a pounds field');
  assert.strictEqual(r.dose, undefined, 'result must not contain a dose field');
});
test('No ounce/lb dose is generated by evaluatePHGuidance', () => {
  const r = c.evaluatePHGuidance(15000, 0.3);
  assert.strictEqual(r.ounces, undefined);
  assert.strictEqual(r.pounds, undefined);
});
test('Constants 5 and 6 are not used for live pH dosing', () => {
  const calcUtilsSrc = fs.readFileSync(path.join(ROOT, 'js', 'calc-utils.js'), 'utf8');
  const calculatorSrc = fs.readFileSync(path.join(ROOT, 'js', 'calculator.js'), 'utf8');
  assert.ok(!/\*\s*6\b/.test(calcUtilsSrc.split('function calculatePHAdjustment')[1] || ''), 'calc-utils.js must not multiply by 6 in the pH function');
  assert.ok(!/\*\s*5\b/.test(calcUtilsSrc.split('function calculatePHAdjustment')[1] || ''), 'calc-utils.js must not multiply by 5 in the pH function');
  assert.ok(!/function\s+phIncreaserOunces|function\s+phReducerOunces/.test(calculatorSrc), 'calculator.js must not retain the old ounce-returning functions');
});
test('No legacy numeric pH path remains callable by the production calculator', () => {
  assert.strictEqual(typeof c.phIncreaserOunces, 'undefined');
  assert.strictEqual(typeof c.phReducerOunces, 'undefined');
  assert.strictEqual(typeof c.evaluatePHGuidance, 'function');
});
test('No page renders r.ounces or phOz for pH output', () => {
  for (const f of ['calculators/pool-ph-calculator.html', 'calculators/hot-tub-ph-calculator.html', 'calculators/chemical-calculator.html']) {
    const html = fs.readFileSync(path.join(ROOT, f), 'utf8');
    assert.ok(!/phOz|phIncreaserOunces|phReducerOunces/.test(html), `${f} must not reference removed pH-ounce identifiers`);
  }
});

// --- Safety ---
test('Safety: pool-ph-calculator.html result includes incremental/retest guidance', () => {
  const html = fs.readFileSync(path.join(ROOT, 'calculators', 'pool-ph-calculator.html'), 'utf8');
  assert.ok(/30.?.?60 minutes/.test(html), 'must state the approved 30-60 minute retest interval');
  assert.ok(/label/i.test(html), 'must direct the user to product label instructions');
  assert.ok(/little at a time|incrementally/i.test(html), 'must instruct incremental addition');
});
test('Safety: hot-tub-ph-calculator.html result includes incremental/retest guidance', () => {
  const html = fs.readFileSync(path.join(ROOT, 'calculators', 'hot-tub-ph-calculator.html'), 'utf8');
  assert.ok(/30.?.?60 minutes/.test(html), 'must state the approved 30-60 minute retest interval');
});
test('Safety: chemical-calculator.html pH guidance line includes retest instruction', () => {
  const html = fs.readFileSync(path.join(ROOT, 'calculators', 'chemical-calculator.html'), 'utf8');
  assert.ok(/retest 30.?.?60 minutes/i.test(html), 'must state the approved retest interval for pH guidance');
});

// --- formula-04 disposition ---
test('formula-04 no longer presents the old unimplemented equation', () => {
  const formulasData = require(path.join(ROOT, 'scripts', 'data', 'formulas-data.js'));
  const f04 = formulasData.find((f) => f.id === 'formula-04');
  assert.ok(!/0\.0833/.test(f04.equation), 'formula-04 must not retain the old, unimplemented 0.0833 constant as a usable equation');
  assert.ok(!/^Acid dose \(fl oz\) =/.test(f04.equation), 'formula-04 must not present a new closed-form equation');
});

// --- Unrelated calculators unchanged ---
const UNRELATED_CALCULATORS = [
  'calculators/pool-volume-calculator.html', 'calculators/spa-volume-calculator.html',
  'calculators/pool-turnover-rate-calculator.html', 'calculators/pool-cyanuric-acid-calculator.html',
  'calculators/saltwater-pool-salt-calculator.html', 'calculators/pool-chlorine-calculator.html',
  'calculators/hot-tub-chlorine-calculator.html', 'calculators/pool-alkalinity-calculator.html',
  'calculators/pool-shock-calculator.html', 'calculators/hot-tub-shock-calculator.html',
  'calculators/volume-calculator.html',
];
test('No unrelated calculator HTML file has a real (non-whitespace) diff against the Phase 7U baseline', () => {
  for (const f of UNRELATED_CALCULATORS) {
    let diff = '';
    try {
      diff = execSync(`git diff -w --stat ${BASELINE_COMMIT} -- "${f}"`, { cwd: ROOT, encoding: 'utf8' }).trim();
    } catch (e) { /* non-fatal */ }
    assert.strictEqual(diff, '', `${f} has an unexpected real diff against baseline: ${diff}`);
  }
});
test('formula-02 (liquid chlorine) and formula-03 (shock) unchanged', () => {
  const formulasData = require(path.join(ROOT, 'scripts', 'data', 'formulas-data.js'));
  const f02 = formulasData.find((f) => f.id === 'formula-02');
  const f03 = formulasData.find((f) => f.id === 'formula-03');
  assert.ok(/0\.013344/.test(f02.equation));
  assert.ok(/0\.013344/.test(f03.equation) && !/800/.test(f03.equation));
});
test('Generic shock divisor (10000) unchanged -- Option B not implemented this phase', () => {
  const calcUtilsSrc = fs.readFileSync(path.join(ROOT, 'js', 'calc-utils.js'), 'utf8');
  assert.ok(/\(g \* ppm\) \/ 10000/.test(calcUtilsSrc));
  assert.ok(!/productSelect|productId|availablePercent/.test(calcUtilsSrc.split('function calculateShock')[1] || ''), 'calculateShock must not have gained a product-selector parameter this phase');
});

// --- No LSI / bromine ---
test('No LSI calculator exists', () => {
  const calcUtilsSrc = fs.readFileSync(path.join(ROOT, 'js', 'calc-utils.js'), 'utf8');
  const calculatorSrc = fs.readFileSync(path.join(ROOT, 'js', 'calculator.js'), 'utf8');
  assert.ok(!/function\s+calculateLSI/i.test(calcUtilsSrc) && !/function\s+calculateLSI/i.test(calculatorSrc));
});
test('No bromine calculator exists', () => {
  const calcUtilsSrc = fs.readFileSync(path.join(ROOT, 'js', 'calc-utils.js'), 'utf8');
  const calculatorSrc = fs.readFileSync(path.join(ROOT, 'js', 'calculator.js'), 'utf8');
  assert.ok(!/function\s+calculateBromine/i.test(calcUtilsSrc) && !/function\s+calculateBromine/i.test(calculatorSrc));
});

// --- No TA/CYA/temperature/product input added ---
test('No TA/CYA/temperature/product input added to the pH calculator pages or functions', () => {
  const calcUtilsSrc = fs.readFileSync(path.join(ROOT, 'js', 'calc-utils.js'), 'utf8');
  const phMatch = calcUtilsSrc.match(/function calculatePHAdjustment\(([^)]*)\)/);
  assert.ok(phMatch && phMatch[1].split(',').map((s) => s.trim()).length === 3, 'calculatePHAdjustment must retain exactly 3 parameters (gallons, currentPh, targetPh)');
  for (const f of ['calculators/pool-ph-calculator.html', 'calculators/hot-tub-ph-calculator.html']) {
    const html = fs.readFileSync(path.join(ROOT, f), 'utf8');
    assert.ok(!/id="alkalinity"|id="cya"|id="temperature"|id="acid-product"/.test(html), `${f} must not have gained a new input field`);
  }
});

// --- No CC input on shock calculators ---
test('No combined-chlorine input added to shock calculators', () => {
  const html = fs.readFileSync(path.join(ROOT, 'calculators', 'pool-shock-calculator.html'), 'utf8');
  assert.ok(!/id="combined-chlorine"/.test(html));
});

// --- Scope: URL/redirect/sitemap/programmatic ---
test('No URL/redirect/sitemap changes', () => {
  const { REDIRECT_SOURCES } = require('./url-policy');
  assert.strictEqual(Object.keys(REDIRECT_SOURCES).length, 6);
  const diff = execSync(`git diff --name-only ${BASELINE_COMMIT} -- sitemap.xml sitemap-index.xml`, { cwd: ROOT, encoding: 'utf8' }).trim();
  assert.strictEqual(diff, '');
});
test('No programmatic-family changes', () => {
  const diff = execSync(`git diff --name-only ${BASELINE_COMMIT} -- programmatic/`, { cwd: ROOT, encoding: 'utf8' }).trim();
  assert.strictEqual(diff, '');
});

// --- Ledger completeness ---
test('DECISION-MATRIX.csv documents every production change with a classification', () => {
  const text = fs.readFileSync(path.join(REPORT_DIR, 'DECISION-MATRIX.csv'), 'utf8').trim();
  const lines = text.split('\n');
  assert.ok(lines.length >= 11, 'expected at least 10 data rows');
  assert.ok(/IMPLEMENTED/.test(text));
});

console.log(`\ntest-phase-7v: ${passed} passed, ${failed} failed.`);
if (failed > 0) process.exit(1);
