/**
 * Cloudflare Pages: _redirects + functions/_middleware.js (301 legacy URLs).
 * Run: node scripts/generate-redirects.js
 */
const fs = require('fs');
const path = require('path');
const {
  LEGACY_CHLORINE_SLUGS,
  EXPLANATION_SLUGS,
  buildExactRedirectMap
} = require('./redirect-rules');
const urlPolicy = require('./url-policy');

const ROOT = path.join(__dirname, '..');
const REDIRECTS_OUT = path.join(ROOT, '_redirects');
const MIDDLEWARE_OUT = path.join(ROOT, 'functions', '_middleware.js');

const lines = [];

for (const slug of LEGACY_CHLORINE_SLUGS) {
  const from = '/programmatic/' + slug;
  const to = '/programmatic/chlorine/' + slug;
  lines.push(from + ' ' + to + ' 301');
  lines.push(from + '.html ' + to + ' 301');
}

for (const slug of EXPLANATION_SLUGS) {
  lines.push(
    '/programmatic/explanation/' + slug + ' /programmatic/explanations/' + slug + ' 301'
  );
  lines.push(
    '/programmatic/explanation/' +
      slug +
      '.html /programmatic/explanations/' +
      slug +
      ' 301'
  );
  lines.push('/explanations/' + slug + ' /programmatic/explanations/' + slug + ' 301');
  lines.push(
    '/explanations/' + slug + '.html /programmatic/explanations/' + slug + ' 301'
  );
}

lines.push(
  '/programmatic/explanation/* /programmatic/explanations/:splat 301',
  '/explanations/* /programmatic/explanations/:splat 301'
);

// Phase 7C URL consolidation: duplicate calculator + legacy chart pages.
for (const [relPath, destination] of Object.entries(urlPolicy.REDIRECT_SOURCES)) {
  const from = '/' + relPath.replace(/\.html$/, '').replace(/\/index$/, '');
  lines.push(from + ' ' + destination + ' 301');
  lines.push(from + '.html ' + destination + ' 301');
}

fs.writeFileSync(REDIRECTS_OUT, lines.join('\n') + '\n', 'utf8');

const exact = buildExactRedirectMap();
const entries = [...exact.entries()]
  .map(([from, to]) => "  ['" + from + "', '" + to + "']")
  .join(',\n');

const middleware =
  '/**\n' +
  ' * Enforces 301 redirects before static assets (legacy paths + explanation typos).\n' +
  ' * Generated by scripts/generate-redirects.js — do not edit by hand.\n' +
  ' */\n' +
  'const EXACT = new Map([\n' +
  entries +
  '\n]);\n\n' +
  'function normalizePath(pathname) {\n' +
  '  let p = pathname;\n' +
  "  if (p.length > 1 && p.endsWith('/')) p = p.slice(0, -1);\n" +
  "  if (p.endsWith('.html')) p = p.slice(0, -5);\n" +
  '  return p;\n' +
  '}\n\n' +
  'export async function onRequest(context) {\n' +
  '  const url = new URL(context.request.url);\n' +
  '  const path = normalizePath(url.pathname);\n' +
  '  const dest = EXACT.get(path);\n' +
  '  if (dest) {\n' +
  '    return Response.redirect(url.origin + dest, 301);\n' +
  '  }\n' +
  "  if (path.startsWith('/programmatic/explanation/')) {\n" +
  "    const rest = path.slice('/programmatic/explanation'.length);\n" +
  "    return Response.redirect(url.origin + '/programmatic/explanations' + rest, 301);\n" +
  '  }\n' +
  "  if (path.startsWith('/explanations/')) {\n" +
  "    const rest = path.slice('/explanations'.length);\n" +
  "    return Response.redirect(url.origin + '/programmatic/explanations' + rest, 301);\n" +
  '  }\n' +
  '  return context.next();\n' +
  '}\n';

if (!fs.existsSync(path.join(ROOT, 'functions'))) {
  fs.mkdirSync(path.join(ROOT, 'functions'), { recursive: true });
}
fs.writeFileSync(MIDDLEWARE_OUT, middleware, 'utf8');

console.log(
  'generate-redirects: wrote _redirects (' +
    lines.length +
    ' rules) and functions/_middleware.js'
);
